-- creative_arms: Thompson Sampling bandit state per ad creative variant
CREATE TABLE IF NOT EXISTS creative_arms (
  arm_id       TEXT        PRIMARY KEY,
  campaign_id  TEXT        NOT NULL,
  tenant_id    TEXT        NOT NULL,
  alpha        FLOAT       NOT NULL DEFAULT 1,   -- successes + 1
  beta         FLOAT       NOT NULL DEFAULT 1,   -- failures + 1
  impressions  INTEGER     NOT NULL DEFAULT 0,
  clicks       INTEGER     NOT NULL DEFAULT 0,
  conversions  INTEGER     NOT NULL DEFAULT 0,
  spend        NUMERIC(12,2) NOT NULL DEFAULT 0,
  revenue      NUMERIC(12,2) NOT NULL DEFAULT 0,
  ctr          FLOAT       NOT NULL DEFAULT 0,
  roas         FLOAT       NOT NULL DEFAULT 0,
  is_active    BOOLEAN     NOT NULL DEFAULT true,
  is_paused    BOOLEAN     NOT NULL DEFAULT false,
  is_winner    BOOLEAN     NOT NULL DEFAULT false,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_creative_arms_campaign  ON creative_arms (campaign_id, tenant_id, is_active);
CREATE INDEX IF NOT EXISTS idx_creative_arms_winner    ON creative_arms (campaign_id, is_winner);

-- seo_content_briefs: content briefs generated by ContentClusterEngine
CREATE TABLE IF NOT EXISTS seo_content_briefs (
  id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  slug            TEXT        NOT NULL UNIQUE,
  title           TEXT        NOT NULL,
  target_keyword  TEXT        NOT NULL,
  search_intent   TEXT        NOT NULL,
  word_count      INTEGER     NOT NULL DEFAULT 1500,
  priority        TEXT        NOT NULL DEFAULT 'medium',
  status          TEXT        NOT NULL DEFAULT 'draft',  -- draft|approved|published
  pillar_slug     TEXT,
  content_json    JSONB,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- admin_agent_sessions: persisted super-agent session state
CREATE TABLE IF NOT EXISTS admin_agent_sessions (
  session_id  TEXT        PRIMARY KEY,
  admin_id    TEXT        NOT NULL,
  history     JSONB       NOT NULL DEFAULT '[]',
  context     JSONB       NOT NULL DEFAULT '{}',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_agent_sessions_admin ON admin_agent_sessions (admin_id, updated_at DESC);
